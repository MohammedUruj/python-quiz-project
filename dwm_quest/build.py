#!/usr/bin/env python3
"""Build DWM QUEST into single-file HTML pages.

    python dwm_quest/build.py

Outputs:
  dist/dwm-quest.html             page body for publishing as a claude.ai Artifact (the platform adds <!doctype>/<head>)
  dist/dwm-quest-standalone.html  complete HTML document for opening locally / static hosting (demo mode)

The assessment answer key in content/assessment_bank.json is replaced by salted hashes; the
plain answers are never written to dist/.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
DIST = ROOT / "dist"
ORDER = ["config.js", "logic.js", "questions.gen.js", "content.js", "ui.js", "store.js",
         "missions.js", "station.js", "assessment.js", "admin.js", "app.js"]
M32 = 0xFFFFFFFF


def imul(a, b):
    return (a * b) & M32


def cyrb53(s, seed=0):
    """Python port of logic.js hash(); must stay byte-for-byte identical."""
    h1 = 0xDEADBEEF ^ seed
    h2 = 0x41C6CE57 ^ seed
    for ch in s:
        c = ord(ch)
        h1 = imul(h1 ^ c, 2654435761)
        h2 = imul(h2 ^ c, 1597334677)
    h1 = imul(h1 ^ (h1 >> 16), 2246822507) ^ imul(h2 ^ (h2 >> 13), 3266489909)
    h2 = imul(h2 ^ (h2 >> 16), 2246822507) ^ imul(h1 ^ (h1 >> 13), 3266489909)
    n = 4294967296 * (2097151 & h2) + (h1 & M32)
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    out = ""
    while True:
        n, r = divmod(n, 36)
        out = digits[r] + out
        if n == 0:
            return out


def answer_key(salt, qid, option_id):
    return cyrb53(f"{salt}|{qid}|{option_id}", 7)


def build_questions():
    bank = json.loads((ROOT / "content" / "assessment_bank.json").read_text(encoding="utf-8"))
    qs = []
    for q in bank["questions"]:
        ids = [o["id"] for o in q["options"]]
        assert q["answer"] in ids, f"{q['id']}: answer not among options"
        qs.append({"id": q["id"], "area": q["area"], "scenario": q["scenario"], "text": q["text"],
                   "options": q["options"], "explain": q["explain"],
                   "key": answer_key(bank["salt"], q["id"], q["answer"])})
    public = {"version": bank["version"], "salt": bank["salt"], "questions": qs}
    js = "// GENERATED by build.py from content/assessment_bank.json. Do not edit.\n" \
         "window.DWM = window.DWM || {};\nDWM.QUESTION_BANK = " + json.dumps(public, ensure_ascii=False, indent=1) + ";\n"
    (SRC / "questions.gen.js").write_text(js, encoding="utf-8")
    return bank


def main():
    build_questions()
    shell = (SRC / "shell.html").read_text(encoding="utf-8")
    css = (SRC / "styles.css").read_text(encoding="utf-8")
    scripts = []
    for name in ORDER:
        code = (SRC / name).read_text(encoding="utf-8")
        assert "</script" not in code.lower(), f"{name} contains </script"
        scripts.append(f"// ---- {name} ----\n{code}")
    page = shell.replace("/*STYLES*/", css).replace("/*SCRIPTS*/", "\n".join(scripts))
    assert '"answer"' not in page, "plain answer key leaked into the page"
    DIST.mkdir(exist_ok=True)
    (DIST / "dwm-quest.html").write_text(page, encoding="utf-8")
    standalone = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
                  '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n'
                  "<style>[hidden]{display:none!important}body{margin:0}img{max-width:100%}</style>\n"
                  "</head>\n<body>\n" + page + "\n</body>\n</html>\n")
    (DIST / "dwm-quest-standalone.html").write_text(standalone, encoding="utf-8")
    print(f"Built {DIST / 'dwm-quest.html'} ({len(page) // 1024} KB) and dwm-quest-standalone.html")


if __name__ == "__main__":
    main()
